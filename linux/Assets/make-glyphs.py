# Writes ../Glyphs.cs: the icons File Labs uses, by role, as characters of FluentSystemIcons-Regular.ttf (MIT, Microsoft's
# own Fluent icons; Segoe Fluent Icons can't be shipped outside Windows). Run again after adding a role.
import json, os
here = os.path.dirname(os.path.abspath(__file__))
font = json.load(open(os.path.join(here, 'FluentSystemIcons-Regular.json')))
roles = {
    'Folder': 'folder', 'FolderOpen': 'folder_open', 'NewFolder': 'folder_add', 'Document': 'document', 'NewFile': 'document_add',
    'Image': 'image', 'Video': 'video', 'Music': 'music_note_2', 'Archive': 'folder_zip', 'Program': 'app_generic',
    'Code': 'code', 'Pdf': 'document_pdf', 'Up': 'arrow_up', 'Down': 'arrow_down', 'Back': 'arrow_left', 'Forward': 'arrow_right',
    'Refresh': 'arrow_clockwise', 'Add': 'add', 'Close': 'dismiss', 'More': 'more_horizontal', 'Settings': 'settings',
    'Pin': 'pin', 'Unpin': 'pin_off', 'Link': 'link', 'Filter': 'filter', 'Star': 'star', 'Check': 'checkmark',
    'Delete': 'delete', 'EmptyBin': 'delete_dismiss', 'Terminal': 'window_console', 'SelectAll': 'select_all_on',
    'Play': 'play', 'Pause': 'pause', 'Restore': 'arrow_reset', 'Paste': 'clipboard_paste', 'WhatsNew': 'megaphone',
    'Undo': 'arrow_undo', 'OpenWith': 'open', 'Eye': 'eye', 'EyeOff': 'eye_off', 'Bin': 'archive', 'Warning': 'warning',
    'Shield': 'shield', 'Desktop': 'desktop', 'Games': 'games', 'Home': 'home', 'History': 'history', 'Clock': 'clock',
    'Download': 'arrow_download', 'Help': 'question', 'Update': 'arrow_sync', 'Pizza': 'food_pizza', 'Compare': 'split_vertical', 'OtherPane': 'panel_right',
    'Transfers': 'arrow_swap', 'Rename': 'rename', 'Movie': 'movies_and_tv', 'Selection': 'checkbox_checked',
    'IconsView': 'grid', 'ListView': 'list', 'DetailsView': 'text_bullet_list_square', 'View': 'eye_tracking', 'Cut': 'cut',
    'Copy': 'copy', 'Duplicates': 'document_copy', 'Move': 'folder_arrow_right', 'Minimize': 'subtract', 'Maximize': 'maximize',
    'Unmaximize': 'square_multiple', 'Info': 'info', 'Drive': 'hard_drive', 'NetworkDrive': 'cloud', 'Computer': 'laptop',
    'NewTab': 'tab_add', 'Zip': 'folder_zip', 'Grip': 're_order_dots_vertical', 'ChevronRight': 'chevron_right',
    'ChevronDown': 'chevron_down', 'Search': 'search', 'Sort': 'arrow_sort', 'Usb': 'usb_stick', 'Trash': 'delete',
}
lines, missing = [], []
for role, name in roles.items():
    key = next((k for k in (f'ic_fluent_{name}_20_regular', f'ic_fluent_{name}_24_regular') if k in font), None)
    if key is None: missing.append(f'{role}={name}'); continue
    lines.append(f'    public const string {role} = "\\u{font[key]:04X}"; // {name}')
if missing: raise SystemExit('not in the font: ' + ', '.join(missing))
out = ['// Generated by Assets/make-glyphs.py: File Labs\' icons by role, in FluentSystemIcons-Regular.ttf.', 'namespace FileExplorer;',
       '', 'static class Glyph', '{', '    public const string Font = "avares://filelabs/Assets#FluentSystemIcons-Regular";', *lines, '}', '']
open(os.path.join(here, '..', 'Glyphs.cs'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print(len(lines), 'glyphs')
